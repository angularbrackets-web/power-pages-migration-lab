// Builds parity-report.md from the C# TRX results and the JS port.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const rules = require('../js/rules.js');

const [trxPath, dotnetTxt, nodeTxt, outPath] = process.argv.slice(2);

// C# outcome per vector id, read from the TRX (theory display names contain the id).
const trx = fs.readFileSync(trxPath, 'utf8');
const csharp = {};
for (const m of trx.matchAll(/<UnitTestResult\b[^>]*>/g)) {
  const tag = m[0];
  const name = /testName="([^"]*)"/.exec(tag)[1];
  const outcome = /outcome="([^"]*)"/.exec(tag)[1];
  const id = /\b([EVFS][0-9]-[A-Z]?[0-9]{2})\b/.exec(name);
  if (id) { csharp[id[1]] = outcome === 'Passed' ? 'pass' : 'FAIL'; }
}

const dir = path.join(__dirname, '..', '..', 'legacy-logic', 'test-vectors');
const cases = [];
for (const f of ['eligibility.json', 'validation.json', 'fees.json', 'status.json']) {
  cases.push(...JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
}

const show = (v) => (v !== null && typeof v === 'object') ? JSON.stringify(v) : String(v);
let matched = 0;
const rows = cases.map((c) => {
  const actual = rules.runVector(c);
  const jsOk = JSON.stringify(actual) === JSON.stringify(c.expected);
  const cs = csharp[c.id] || 'missing';
  const match = cs === 'pass' && jsOk;
  if (match) { matched++; }
  return `| ${c.id} | ${c.rule} | \`${show(c.expected)}\` | ${cs} | ${jsOk ? 'pass' : 'FAIL'} (\`${show(actual)}\`) | ${match ? 'yes' : 'no'} |`;
});

const grab = (txt, re) => (re.exec(fs.readFileSync(txt, 'utf8')) || [, '?'])[1];
const csTotal = grab(dotnetTxt, /Total:\s*(\d+)/);
const csPassed = grab(dotnetTxt, /Passed:\s*(\d+)/);
const jsTests = grab(nodeTxt, /ℹ tests (\d+)/);
const jsPass = grab(nodeTxt, /ℹ pass (\d+)/);

const out = [
  '# Parity report: C# rules vs JavaScript port',
  '',
  'Generated by `conversion/parity/run-parity.sh`. Both implementations run the same',
  'vector files in `legacy-logic/test-vectors/`. The C# column is the xUnit outcome',
  'for that vector (from the TRX file). The JS column is the outcome of',
  '`conversion/js/rules.js` with the value it returned. A row matches when both pass',
  'against the shared expected value.',
  '',
  `Summary: ${matched} of ${cases.length} vectors match. C# tests: ${csPassed} of ${csTotal} passed. JS tests: ${jsPass} of ${jsTests} passed.`,
  '',
  '| Vector | Rule | Expected | C# | JS | Match |',
  '|--------|------|----------|----|----|-------|',
  ...rows,
  ''
].join('\n');
fs.writeFileSync(outPath, out);
console.log(`Wrote ${outPath}: ${matched}/${cases.length} match`);
process.exitCode = matched === cases.length ? 0 : 1;
